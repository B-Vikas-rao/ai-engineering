# Variables in Python

# String
name = "Vikas"

# Integer
age = 20

# Float
cgpa = 8.5

# Boolean
is_student = True

# Print variable values
print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Student:", is_student)

# Print variable types
print(type(name))
print(type(age))
print(type(cgpa))
print(type(is_student))

# Output:
# Name: Vikas
# Age: 20
# CGPA: 8.5
# Student: True
# <class 'str'>
# <class 'int'>
# <class 'float'>
# <class 'bool'>