# Escape Characters in Python

# \n - New line
print("Hello\nWorld")

# \t - Tab space
print("Python\tAI")

# \" - Double quotes
print("He said, \"Hello!\"")

# \' - Single quote
print('It\'s Python')

# \\ - Backslash
print("C:\\Users\\Vikas")

# Output:
# Hello
# World
# Python    AI
# He said, "Hello!"
# It's Python
# C:\Users\Vikas