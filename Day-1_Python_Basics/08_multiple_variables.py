# Multiple Variables in Python
# Assigning multiple values
name, age, city = "Vikas", 20, "Hyderabad"
print("Name:", name)
print("Age:", age)
print("City:", city)
# Assigning the same value to multiple variables
x = y = z = 100
print("x =", x)
print("y =", y)
print("z =", z)

# Output:
# Name: Vikas
# Age: 20
# City: Hyderabad
# x = 100
# y = 100
# z = 100