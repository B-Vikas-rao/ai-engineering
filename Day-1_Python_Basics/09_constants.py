# Constants in Python

# Constants are written in UPPER_CASE by convention
PI = 3.14159
MAX_USERS = 100
COLLEGE = "CVR College of Engineering"

print("PI:", PI)
print("Maximum Users:", MAX_USERS)
print("College:", COLLEGE)

# Output:
# PI: 3.14159
# Maximum Users: 100
# College: CVR College of Engineering