# print() function in Python

print("Hello, World!")
print("Welcome to AI Engineering")

# Printing multiple values
print("Name:", "Vikas")
print("Age:", 20)

# Using sep
print("Python", "AI", "ML", sep=" | ")

# Using end
print("Hello", end=" ")
print("World")

# Output:
# Hello, World!
# Welcome to AI Engineering
# Name: Vikas
# Age: 20
# Python | AI | ML
# Hello World