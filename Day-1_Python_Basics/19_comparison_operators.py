# Comparison Operators in Python

a = 10
b = 20
print("a == b :", a == b)
print("a != b :", a != b)
print("a > b :", a > b)
print("a < b :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)

# Output:
# a == b : False
# a != b : True
# a > b : False
# a < b : True
# a >= b : False
# a <= b : True