# f-Strings in Python
name = "Vikas"
age = 20
cgpa = 8.5678
# Display variables using f-strings
print(f"Name: {name}")
print(f"Age: {age}")
print(f"CGPA: {cgpa}")
# Formatting decimal places
print(f"CGPA: {cgpa:.2f}")
# Using expressions
print(f"Next Year Age: {age + 1}")

# Output:
# Name: Vikas
# Age: 20
# CGPA: 8.5678
# CGPA: 8.57
# Next Year Age: 21