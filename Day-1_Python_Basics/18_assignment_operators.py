# Assignment Operators in Python
x = 10
print("x =", x)
x += 5
print("x += 5 :", x)
x -= 3
print("x -= 3 :", x)
x *= 2
print("x *= 2 :", x)
x /= 4
print("x /= 4 :", x)
x //= 2
print("x //= 2 :", x)
x %= 2
print("x %= 2 :", x)
x **= 3
print("x **= 3 :", x)

# Output:
# x = 10
# x += 5 : 15
# x -= 3 : 12
# x *= 2 : 24
# x /= 4 : 6.0
# x //= 2 : 3.0
# x %= 2 : 1.0
# x **= 3 : 1.0