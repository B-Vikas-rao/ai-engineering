# Type Conversion in Python
# Integer to Float
num = 10
print(float(num))
# Float to Integer
price = 99.99
print(int(price))
# Integer to String
age = 20
print(str(age))
# String to Integer
number = "100"
print(int(number))
# Integer to Boolean
value = 1
print(bool(value))
# Boolean to Integer
status = True
print(int(status))

# Output:
# 10.0
# 99
# 20
# 100
# True
# 1