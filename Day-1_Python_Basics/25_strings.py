# Strings in Python

# Creating strings
name = "Vikas"
course = 'AI Engineering'

print(name)
print(course)

# Multi-line string
message = """
Python is used for
AI and Machine Learning
"""

print(message)

# Checking string type
print(type(name))

# Output:
# Vikas
# AI Engineering
# 
# Python is used for
# AI and Machine Learning
# 
# <class 'str'>