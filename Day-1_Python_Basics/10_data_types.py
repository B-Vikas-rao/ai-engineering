# Data Types in Python
# Integer
age = 20
# Float
cgpa = 8.5
# String
name = "Vikas"
# Boolean
is_student = True
# List
languages = ["Python", "Java", "C++"]
# Tuple
colors = ("Red", "Green", "Blue")
# Set
numbers = {10, 20, 30}
# Dictionary
student = {
    "Name": "Vikas",
    "Age": 20
}
# None Type
data = None
# Print values and their data types
print(age, type(age))
print(cgpa, type(cgpa))
print(name, type(name))
print(is_student, type(is_student))
print(languages, type(languages))
print(colors, type(colors))
print(numbers, type(numbers))
print(student, type(student))
print(data, type(data))

# Output:
# 20 <class 'int'>
# 8.5 <class 'float'>
# Vikas <class 'str'>
# True <class 'bool'>
# ['Python', 'Java', 'C++'] <class 'list'>
# ('Red', 'Green', 'Blue') <class 'tuple'>
# {10, 20, 30} <class 'set'>
# {'Name': 'Vikas', 'Age': 20} <class 'dict'>
# None <class 'NoneType'>