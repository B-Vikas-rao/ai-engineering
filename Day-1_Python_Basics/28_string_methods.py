# String Methods in Python

text = "python programming"

# Convert to uppercase
print(text.upper())

# Convert to lowercase
print(text.lower())

# Capitalize first letter
print(text.capitalize())

# Replace a word
print(text.replace("python", "AI"))

# Find length
print(len(text))

# Output:
# PYTHON PROGRAMMING
# python programming
# Python programming
# AI programming
