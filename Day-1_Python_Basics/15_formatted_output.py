# Formatted Output in Python

name = "Vikas"
age = 20
cgpa = 8.5

# Using comma
print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)

# Using f-string
print(f"Name: {name}")
print(f"Age: {age}")
print(f"CGPA: {cgpa}")

# Output:
# Name: Vikas
# Age: 20
# CGPA: 8.5
# Name: Vikas
# Age: 20
# CGPA: 8.5