a = list(map(int, input("Enter elements: ").split()))

print("Original List:", a)

print("a[:]:", a[:])

print("a[1:4]:", a[1:4])

print("a[:3]:", a[:3])

print("a[2:]:", a[2:])

print("a[-1]:", a[-1])

print("a[-3:]:", a[-3:])

print("a[:-2]:", a[:-2])

print("a[::-1]:", a[::-1])

print("a[::2]:", a[::2])

print("a[1::2]:", a[1::2])

print("a[::-2]:", a[::-2])